import numpy as np


def gridworld_policy_evaluation(theta=1e-4, gamma=1.0):
  # Initialize a 4x4 value function array to zero
  # States 0 and 15 are terminal states with value 0
  V = np.zeros((4, 4))

  # Actions: up, down, left, right
  actions = [(-1, 0), (1, 0), (0, -1), (0, 1)]
  action_prob = 0.25  # Equiprobable random policy (1/4 for each action)

  while True:
    delta = 0
    # Copy current value function for synchronous update
    V_new = np.copy(V)

    for i in range(4):
      for j in range(4):
        # Skip terminal states (top-left [0,0] and bottom-right [3,3])
        if (i == 0 and j == 0) or (i == 3 and j == 3):
          continue

        v = 0
        for action in actions:
          # Determine next state
          ni, nj = i + action[0], j + action[1]

          # If action takes the agent off the grid, stay in the same state
          if ni < 0 or ni >= 4 or nj < 0 or nj >= 4:
            ni, nj = i, j

          # Reward is -1 on all transitions until terminal state
          reward = -1
          # Bellman equation update for equiprobable random policy
          v += action_prob * (reward + gamma * V[ni, nj])

        delta = max(delta, abs(v - V[i, j]))
        V_new[i, j] = v

    V = V_new

    # Stop if change is smaller than threshold theta
    if delta < theta:
      break

  return np.round(V, 2)



import numpy as np

# Define grid size (4x4)
GRID_SIZE = 4
num_states = GRID_SIZE * GRID_SIZE
actions = [(-1, 0), (1, 0), (0, -1), (0, 1)]  # Up, Down, Left, Right
action_prob = 1.0 / len(actions)              # Equiprobable random policy (0.25)

# Terminal states: top-left (0,0) and bottom-right (3,3) are the same terminal state
terminal_states = {(0, 0), (3, 3)}

def get_next_state(state, action):
    if state in terminal_states:
        return state, 0.0

    next_r = state[0] + action[0]
    next_c = state[1] + action[1]

    # If action takes agent off grid, state remains unchanged
    if next_r < 0 or next_r >= GRID_SIZE or next_c < 0 or next_c >= GRID_SIZE:
        next_state = state
    else:
        next_state = (next_r, next_c)

    reward = -1.0
    return next_state, reward

def policy_evaluation(target_k=None, theta=1e-4):
    # Initialize value function V(s) = 0 for all s
    V = np.zeros((GRID_SIZE, GRID_SIZE))

    k = 0
    while True:
        if target_k is not None and k == target_k:
            return V

        delta = 0.0
        V_new = np.copy(V)

        for r in range(GRID_SIZE):
            for c in range(GRID_SIZE):
                state = (r, c)
                if state in terminal_states:
                    V_new[r, c] = 0.0
                    continue

                v_sum = 0.0
                for action in actions:
                    next_state, reward = get_next_state(state, action)
                    v_sum += action_prob * (reward + V[next_state])

                delta = max(delta, abs(v_sum - V_new[r, c]))
                V_new[r, c] = v_sum

        V = V_new
        k += 1

        # Check convergence for k = infinity
        if target_k is None and delta < theta:
            print(f"Converged at iteration k = {k}")
            return V

# Calculate for k = 0, 1, 2, 3, 10, infinity
k_values = [0, 1, 2, 3, 10, 'infinity']

for k_val in k_values:
    if k_val == 'infinity':
        res = policy_evaluation(target_k=None)
    else:
        res = policy_evaluation(target_k=k_val)
    print(f"\n--- Value Function V_k for k = {k_val} ---")
    print(np.round(res, 2))